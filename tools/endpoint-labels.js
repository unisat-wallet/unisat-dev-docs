function endpointSidebarLabel(module, { opId, summary, route, operation }) {
  const override = operation?.["x-sidebar-label"];
  if (typeof override === "string" && override.trim()) return override.trim();
  if (Object.hasOwn(labels, opId)) return labels[opId];

  if (module.endsWith("-marketplace")) {
    const action = opId.replace(/^(create|confirm)(?:Brc20|Runes|Alkanes|DomainMarket|Market)/, "$1");
    if (Object.hasOwn(marketplaceActions, action)) return marketplaceActions[action];
  }

  if (module === "brc20-swap") {
    const action = route.split("/").at(-1);
    if (Object.hasOwn(swapLabels, action)) return swapLabels[action];
  }

  return summary || opId;
}

